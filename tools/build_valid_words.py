#!/usr/bin/env python3
"""Build js/valid-words.js, the dictionary of accepted 5-letter guesses.

Source: FrequencyWords by Hermit Dave (OpenSubtitles 2018, Arabic),
https://github.com/hermitdave/FrequencyWords — content licensed CC BY-SA 4.0.

Usage:
    curl -L -o ar_full.txt \
      https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/ar/ar_full.txt
    python3 tools/build_valid_words.py ar_full.txt js/valid-words.js
"""
import re
import sys

LETTERS = set("ابتثجحخدذرزسشصضطظعغفقكلمنهوي" + "ةىءؤئ")
ALEF = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا"})
DIACRITICS = re.compile("[ً-ٰٟـ]")
MIN_COUNT = 20  # drops typos and one-off transliterations
STUTTER = re.compile(r"^اا|(.)\1\1")  # "ااتصل", "ااااه": subtitle stammers


def normalize(word):
    return DIACRITICS.sub("", word).translate(ALEF)


def main(src, dest):
    counts = {}
    with open(src, encoding="utf-8") as fh:
        for line in fh:
            parts = line.split()
            if len(parts) != 2:
                continue
            word = normalize(parts[0])
            if len(word) == 5 and all(ch in LETTERS for ch in word) and not STUTTER.search(word):
                counts[word] = counts.get(word, 0) + int(parts[1])
    words = sorted(w for w, c in counts.items() if c >= MIN_COUNT)
    with open(dest, "w", encoding="utf-8") as out:
        out.write(
            "// Accepted guesses: 5-letter Arabic words, hamza-on-alef normalized to ا.\n"
            "// Derived from FrequencyWords by Hermit Dave (OpenSubtitles 2018),\n"
            "// https://github.com/hermitdave/FrequencyWords, licensed CC BY-SA 4.0.\n"
            "// This filtered list is likewise shared under CC BY-SA 4.0.\n"
            "// Generated by tools/build_valid_words.py — do not edit by hand.\n"
        )
        out.write('(function (root) {\n  var list = "' + " ".join(words) + '".split(" ");\n')
        out.write(
            "  if (typeof module === \"object\" && module.exports) module.exports = list;\n"
            "  else root.HZ_VALID_WORDS = list;\n"
            "})(typeof self !== \"undefined\" ? self : this);\n"
        )
    print(f"{len(words)} words -> {dest}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
